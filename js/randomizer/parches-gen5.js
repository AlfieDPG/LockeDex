// Aplica un parche IPS a «destino» (un Uint8Array, que no crece) y lo devuelve
export function aplicarIPS(destino, ips) {
  let p = 5; // «PATCH»
  for (;;) {
    const donde = (ips[p] << 16) | (ips[p + 1] << 8) | ips[p + 2];
    if (donde === 0x454f46) break; // «EOF»
    const largo = (ips[p + 3] << 8) | ips[p + 4];
    p += 5;
    if (largo === 0) {
      const cuantos = (ips[p] << 8) | ips[p + 1];
      destino.fill(ips[p + 2], donde, donde + cuantos);
      p += 3;
    } else {
      destino.set(ips.subarray(p, p + largo), donde);
      p += largo;
    }
  }
  return destino;
}
